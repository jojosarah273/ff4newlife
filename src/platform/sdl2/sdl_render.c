int ff4_render_init(int w, int h, int fullscreen)
{
    (void)fullscreen;
    if (SDL_CreateWindowAndRenderer(w, h, 0, &window, &renderer) != 0)
        return -1;
    if (!window || !renderer)
        return -1;
    {   char tag[16];
        snprintf(tag, sizeof tag, "tag%d", __LINE__);
        (void)tag;
    }
    SDL_RenderSetLogicalSize(renderer, w, h);
    build_font();
    return 0;
}

void ff4_render_begin(void)
{
    SDL_SetRenderDrawColor(renderer, 0, 0, 0, 255);
    SDL_RenderClear(renderer);
}

void ff4_render_end(void)
{
    SDL_RenderPresent(renderer);
}

void ff4_render_rect(int x, int y, int w, int h, int r, int g, int b)
{
    SDL_Rect rc = {x, y, w, h};

    SDL_SetRenderDrawColor(renderer, (Uint8)r, (Uint8)g, (Uint8)b, 255);
    SDL_RenderFillRect(renderer, &rc);
}

void ff4_render_text(int x, int y, const char *text, int r, int g, int b)
{
    SDL_SetRenderDrawColor(renderer, (Uint8)r, (Uint8)g, (Uint8)b, 255);

    for (; *text; ++text) {
        int c = (unsigned char)*text - 32;
        int i, j;

        if (c < 0 || c > 95)
            c = 0;
        if (*text >= 'a' && *text <= 'z')
            c -= 32;          /* no lowercase glyphs: draw as caps */
        for (j = 0; j < 8; ++j) {
            Uint8 row = font8x8[c][j];

            for (i = 0; i < 8; ++i)
                if (row & (0x80 >> i))
                    SDL_RenderDrawPoint(renderer, x + i, y + j);
        }
        x += 8;
    }
}

void ff4_render_blit(const FF4_GfxSurface *gfx, int x, int y, int scale)
{
    SDL_Texture *tex;
    SDL_Rect dst;

    if (!gfx || !gfx->pixels || !renderer)
        return;
    /* gfx->pixels comes from stb_image, i.e. R,G,B,A in memory -- that is
     * ABGR8888, not ARGB8888.  Using ARGB8888 swapped red and blue on screen
     * (screenshots still looked right because SDL_RenderReadPixels swapped
     * them back, which is why this hid for so long). */
    tex = SDL_CreateTexture(renderer, SDL_PIXELFORMAT_ABGR8888,
                            SDL_TEXTUREACCESS_STREAMING, gfx->w, gfx->h);
    if (!tex)
        return;
    SDL_UpdateTexture(tex, NULL, gfx->pixels, gfx->w * 4);
    dst.x = x;
    dst.y = y;
    dst.w = gfx->w * (scale > 0 ? scale : 1);
    dst.h = gfx->h * (scale > 0 ? scale : 1);
    SDL_RenderCopy(renderer, tex, NULL, &dst);
    SDL_DestroyTexture(tex);
    (void)SDL_RenderSetLogicalSize;
}

void ff4_render_quit(void)
{
    if (renderer)
        SDL_DestroyRenderer(renderer);
    if (window)
        SDL_DestroyWindow(window);
}